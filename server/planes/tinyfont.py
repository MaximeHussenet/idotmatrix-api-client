_FONTS = {
    "3x5": (FONT, 4),
    "4x6": (FONT46, 5),
    "5x7": (FONT57, 6),
}


def draw_text(img: Image.Image, x: int, y: int, text: str, color,
              stretch: int = 0, font: str = "3x5") -> None:
    """Render text; stretch=n repeats the middle glyph row n extra times."""
    glyphs, pitch = _FONTS[font]
    w, h = img.size
    for ch in text.upper():
        glyph = glyphs.get(ch, glyphs["?"])
        mid = len(glyph) // 2
        rows = glyph[:mid] + (glyph[mid],) * stretch + glyph[mid:]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "1" and 0 <= x + gx < w and 0 <= y + gy < h:
                    img.putpixel((x + gx, y + gy), color)
        x += pitch


def text_width(text: str, font: str = "3x5") -> int:
    return len(text) * _FONTS[font][1] - 1 if text else 0
